#!/usr/bin/env node
/**
 * Ingest reviewed `.teaching.md` lecture blueprints.
 *
 *   node scripts/ingest-teaching-md.mjs            validate + regenerate local artifacts (default, no network)
 *   node scripts/ingest-teaching-md.mjs --check    validate only, write nothing (CI)
 *   node scripts/ingest-teaching-md.mjs --apply    ALSO upsert rows into the remote Supabase project.
 *                                                  Requires SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in the
 *                                                  environment (never read from files). Remote write: only run
 *                                                  after the project owner approves.
 *
 * Artifacts (generated, committed):
 *   apps/web/src/data/teaching.concepts.generated.json   bundled copy used by the whiteboard page / offline fallback
 *   supabase/seed/lecture_concepts.generated.sql         idempotent upsert for the SQL editor / `supabase db` flows
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseTeachingMd, contextFromPath, conceptToSql, conceptToRow } from './lib/teaching-md.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has('--check');
const APPLY = args.has('--apply');

function findTeachingFiles() {
  const coursesDir = path.join(ROOT, 'courses');
  const out = [];
  for (const course of fs.readdirSync(coursesDir, { withFileTypes: true })) {
    if (!course.isDirectory()) continue;
    const dir = path.join(coursesDir, course.name, 'teaching');
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) {
      if (f.endsWith('.teaching.md')) out.push(path.join(dir, f));
    }
  }
  return out.sort();
}

const files = findTeachingFiles();
if (files.length === 0) {
  console.error('No .teaching.md files found under courses/*/teaching/.');
  process.exit(1);
}

const all = [];
let failed = false;
for (const file of files) {
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  const { concepts, errors } = parseTeachingMd(fs.readFileSync(file, 'utf8'), contextFromPath(file));
  if (errors.length > 0) {
    failed = true;
    console.error(`\n✗ ${rel}`);
    for (const e of errors) console.error(`  - ${e}`);
  } else {
    const withWidget = concepts.filter((c) => c.widget).length;
    console.log(`✓ ${rel}: ${concepts.length} concepts (${withWidget} with widget, ${concepts.filter((c) => c.status === 'verified').length} verified)`);
  }
  all.push(...concepts);
}
if (failed) {
  console.error('\nValidation failed. Nothing was written.');
  process.exit(1);
}

if (!CHECK_ONLY) {
  const jsonPath = path.join(ROOT, 'apps/web/src/data/teaching.concepts.generated.json');
  fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
  fs.writeFileSync(jsonPath, JSON.stringify(all, null, 2) + '\n');

  const sqlPath = path.join(ROOT, 'supabase/seed/lecture_concepts.generated.sql');
  fs.mkdirSync(path.dirname(sqlPath), { recursive: true });
  fs.writeFileSync(
    sqlPath,
    `-- GENERATED by scripts/ingest-teaching-md.mjs from courses/*/teaching/*.teaching.md. Do not edit by hand.\n` +
      all.map(conceptToSql).join('\n\n') +
      '\n'
  );
  console.log(`\nWrote ${path.relative(ROOT, jsonPath)} and ${path.relative(ROOT, sqlPath)}`);
}

if (APPLY) {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error('--apply needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment.');
    process.exit(1);
  }
  const res = await fetch(`${url.replace(/\/$/, '')}/rest/v1/lecture_concepts?on_conflict=id`, {
    method: 'POST',
    headers: {
      apikey: key,
      Authorization: `Bearer ${key}`,
      'Content-Type': 'application/json',
      Prefer: 'resolution=merge-duplicates,return=minimal',
    },
    body: JSON.stringify(all.map(conceptToRow)),
  });
  if (!res.ok) {
    console.error(`Upsert failed: HTTP ${res.status} ${await res.text()}`);
    process.exit(1);
  }
  console.log(`Upserted ${all.length} concepts into the remote project.`);
}
